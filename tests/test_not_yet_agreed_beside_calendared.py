class TestTheFixtureHoldsWhatItClaims:
    """REQ-TEST-437 criterion 6, first."""

    def test_a_calendar_less_dataset_with_recorded_results(self, page_built):
        recorded = dict(page_built["recorded"])
        assert recorded.get(UNAGREED), "no recorded result for the not-yet-agreed dataset"
        assert recorded.get(CALENDARED), "no recorded result for the calendared dataset"


class TestTheCalendaredDatasetIsUnchanged:
    def _statuses(self, page, page_built):
        page.goto(f"file://{page_built['page']}#/agency/{AGENCY}")
        page.wait_for_function("Number(document.documentElement.dataset.renderCount || 0) >= 1")
        return page.evaluate(f"""() => {{
            const ag = DATA.agencies.find(a => a.id === "{AGENCY}");
            const col = ag.collections.find(c => c.id === "{COLLECTION}");
            const by = Object.fromEntries(col.datasets.map(d => [d.id, d.status]));
            return {{agency: ag.status, collection: col.status, ...by}};
        }}""")

    def test_it_fails_where_counted_would_show(self, page, page_built):
        got = self._statuses(page, page_built)
        assert got[UNAGREED] == "red", got
        assert got[CALENDARED] != "red", got

    def test_the_rollup_is_the_calendared_datasets_own(self, page, page_built):
        got = self._statuses(page, page_built)
        assert got["collection"] == got[CALENDARED], got
        assert got["agency"] == got[CALENDARED], got

    def test_the_page_and_the_build_agree(self, page, page_built):
        got = self._statuses(page, page_built)
        assert page_built["python"] == {UNAGREED: got[UNAGREED], CALENDARED: got[CALENDARED]}

    def test_it_carries_its_marker_and_the_not_counted_line(self, page, page_built):
        self._statuses(page, page_built)
        row = page.locator(f"tr:has(a[href*='dataset/{UNAGREED}'])")
        assert "No delivery schedule agreed yet" in row.inner_text()
        assert "no schedule agreed yet" in page.locator(".not-counted-why").first.inner_text()
