def make_asset(root: Path) -> Path:
    """The fixture asset's folder under a temporary assets/ root."""
    from asset_model.kinds import extraction_folder, extraction_recipe

    pkg = root.parent / "declaration"
    pkg.mkdir()
    (pkg / "recipe.json").write_text(json.dumps(_recipe()))
    for name in ("registry_people.csv", "registry_notes.csv"):
        (pkg / name).write_text("x\n")
    read = extraction_recipe.read(str(pkg))
    folder = root / ASSET
    files = extraction_folder.files_for(read.recipe, folder, introduced="2026-01-01")
    for rel, text in files.items():
        (folder / rel).parent.mkdir(parents=True, exist_ok=True)
        (folder / rel).write_text(text)
    doc = yaml.safe_load((folder / "data-asset.yaml").read_text())
    for key in ("project", "recipe"):
        doc.pop(key, None)
    doc["display_name"] = "Not-yet-agreed fixture asset"
    (folder / "data-asset.yaml").write_text(yaml.safe_dump(doc, sort_keys=False))
    (folder / "calendar.yaml").write_text(yaml.safe_dump(_calendar(), sort_keys=False))
    (folder / "collections").mkdir()
    (folder / "collections" / "registry_study.py").write_text(ADAPTER)
    (folder / "people.yaml").write_text(yaml.safe_dump({"roles": ["qa"], "people": [
        {"email": "tester@example.org", "name": "Tess Ter", "roles": ["qa"]}]}))
    shutil.copy(ROOT / "assets" / "environments.yaml", root / "environments.yaml")
    return folder


